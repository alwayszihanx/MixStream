import 'package:flutter/material.dart';
import 'package:flutter_svg/flutter_svg.dart';

class AppIcon extends StatelessWidget {
  final String icon;
  final double size;
  final Color? color;
  final BoxFit fit;

  const AppIcon(
    this.icon, {
    super.key,
    this.size = 24,
    this.color,
    this.fit = BoxFit.contain,
  });

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final iconColor = color ?? theme.colorScheme.onSurface;
    final path = _resolve(icon);
    if (path == null) {
      return Semantics(
        label: icon,
        child: Icon(Icons.error_outline, size: size, color: iconColor),
      );
    }
    return Semantics(
      label: icon,
      child: SvgPicture.asset(
        path,
        width: size,
        height: size,
        fit: fit,
        colorFilter: ColorFilter.mode(iconColor, BlendMode.srcIn),
      ),
    );
  }
}

String? _resolve(String icon) {
  final name = _normalize(icon);
  final mapped = _overrides[name];
  if (mapped != null) return 'assets/Icons/$mapped.svg';
  return 'assets/Icons/$name.svg';
}

String _normalize(String icon) {
  return icon
      .replaceAll(
        RegExp(r'_(?:rounded|outlined|sharp|filled|outline|fill)$'),
        '',
      )
      .replaceAll('_', '-');
}

